<?php

declare(strict_types=1);

namespace Tmonier\SyliusPlatformHealthPlugin\DependencyInjection;

use Symfony\Component\Config\Definition\Builder\TreeBuilder;
use Symfony\Component\Config\Definition\ConfigurationInterface;
use Tmonier\SyliusPlatformHealthPlugin\ScheduledTasks\BeatInterval;

final class Configuration implements ConfigurationInterface
{
    private const COMMAND = '/^[A-Za-z0-9][A-Za-z0-9:_.-]*$/';

    public function getConfigTreeBuilder(): TreeBuilder
    {
        $treeBuilder = new TreeBuilder('tmonier_sylius_platform_health');
        $treeBuilder->getRootNode()
            ->children()
                ->integerNode('time_budget_ms')
                    ->info('Time budget of each probe, in milliseconds, measured by the runner after the probe returns.')
                    ->defaultValue(500)
                    ->min(1)
                ->end()
                ->integerNode('cache_ttl')
                    ->info('Seconds the results of the probes are shared between administrators (0 disables the cache). The refresh button ignores it.')
                    ->defaultValue(60)
                    ->min(0)
                ->end()
                ->arrayNode('access')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->scalarNode('role')
                            ->info('Role that the PLATFORM_HEALTH_VIEW attribute requires. Use ROLE_PLATFORM_HEALTH_VIEW in production.')
                            ->defaultValue('ROLE_ADMINISTRATION_ACCESS')
                            ->validate()
                                ->ifTrue(static fn (mixed $role): bool => !\is_string($role) || 1 !== preg_match('/^ROLE_\S+$/', $role))
                                ->thenInvalid('The access role must be a Symfony role, starting with "ROLE_" (for instance "ROLE_PLATFORM_HEALTH_VIEW"), got %s.')
                            ->end()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('http')
                    ->info('Public HTTP entry point (/health). Inactive until a token is configured; the token is read from "Authorization: Bearer", never from the URL.')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->scalarNode('token')
                            ->info('Token of the global level: {status, generated_at}. Use an environment variable (%env(PLATFORM_HEALTH_TOKEN)%); an empty value means "not configured".')
                            ->defaultNull()
                            ->beforeNormalization()->ifTrue(static fn (mixed $token): bool => '' === $token)->then(static fn (): null => null)->end()
                        ->end()
                        ->scalarNode('detail_token')
                            ->info('Token of the detail level: identifier, category and status of each check. Must differ from token.')
                            ->defaultNull()
                            ->beforeNormalization()->ifTrue(static fn (mixed $token): bool => '' === $token)->then(static fn (): null => null)->end()
                        ->end()
                        ->booleanNode('liveness')
                            ->info('When true, a request without token receives 200 (no critical check) or 503, with an empty body: for a host health check that sends no header.')
                            ->defaultFalse()
                        ->end()
                        ->integerNode('rate_limit')
                            ->info('Requests per minute and per IP address; the next ones receive 429 without any check being run.')
                            ->defaultValue(30)
                            ->min(1)
                        ->end()
                    ->end()
                    ->validate()
                        ->ifTrue(static fn (array $http): bool => null !== $http['token'] && $http['token'] === $http['detail_token'])
                        ->thenInvalid('http.token and http.detail_token must be different, got the same value.')
                    ->end()
                ->end()
                ->arrayNode('environment')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->integerNode('support_warning_days')
                            ->info('Days before the end of support of PHP, Symfony or Sylius from which the environment probes warn.')
                            ->defaultValue(180)
                            ->min(0)
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('scheduled_tasks')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->arrayNode('heartbeats')
                            ->info('Console commands whose end is recorded, with the rhythm they run at ("15m", "1h", "1d"). An undeclared command is never recorded.')
                            ->example(['tmonier:feeds:generate' => '15m', 'sylius:remove-expired-carts' => '1d'])
                            ->normalizeKeys(false)
                            ->useAttributeAsKey('command')
                            ->scalarPrototype()
                                ->validate()
                                    ->ifTrue(static fn (mixed $beat): bool => null === BeatInterval::seconds($beat))
                                    ->thenInvalid('A heartbeat is a positive duration such as "30s", "15m", "1h" or "1d", got %s.')
                                ->end()
                            ->end()
                            ->validate()
                                ->ifTrue(static fn (array $heartbeats): bool => [] !== array_filter(array_keys($heartbeats), static fn (int|string $command): bool => 1 !== preg_match(self::COMMAND, (string) $command)))
                                ->thenInvalid('A heartbeat is declared for a console command name such as "app:demo:reset", got %s.')
                            ->end()
                        ->end()
                        ->integerNode('warning_beats')
                            ->info('Missed rhythms after which a command without success warns.')
                            ->defaultValue(2)
                            ->min(1)
                        ->end()
                        ->integerNode('critical_beats')
                            ->info('Missed rhythms after which it is critical; above warning_beats.')
                            ->defaultValue(4)
                            ->min(1)
                        ->end()
                    ->end()
                    ->validate()
                        ->ifTrue(static fn (array $tasks): bool => $tasks['critical_beats'] <= $tasks['warning_beats'])
                        ->thenInvalid('critical_beats must be above warning_beats, got %s.')
                    ->end()
                ->end()
                ->arrayNode('data')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->integerNode('connection_warning_ms')
                            ->info('Milliseconds from which the answer of the database to a trivial query warns.')
                            ->defaultValue(500)
                            ->min(1)
                        ->end()
                        ->arrayNode('messenger')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->integerNode('pending_warning')
                                    ->info('Waiting messages of a transport from which data.messenger_pending warns.')
                                    ->defaultValue(100)
                                    ->min(1)
                                ->end()
                                ->integerNode('oldest_warning_minutes')
                                    ->info('Minutes the oldest message of a Doctrine transport may wait before data.messenger_oldest warns.')
                                    ->defaultValue(15)
                                    ->min(1)
                                ->end()
                                ->integerNode('oldest_critical_minutes')
                                    ->info('Minutes beyond which data.messenger_oldest is critical; above oldest_warning_minutes.')
                                    ->defaultValue(60)
                                    ->min(1)
                                ->end()
                                ->integerNode('failed_critical')
                                    ->info('Messages in the failure transports beyond which data.messenger_failed is critical (it warns from one).')
                                    ->defaultValue(100)
                                    ->min(1)
                                ->end()
                            ->end()
                            ->validate()
                                ->ifTrue(static fn (array $messenger): bool => $messenger['oldest_critical_minutes'] <= $messenger['oldest_warning_minutes'])
                                ->thenInvalid('oldest_critical_minutes must be above oldest_warning_minutes, got %s.')
                            ->end()
                        ->end()
                        ->arrayNode('table_growth')
                            ->info('Tables to watch, with the estimated rows from which each warns (critical beyond the double). None by default.')
                            ->useAttributeAsKey('table')
                            ->normalizeKeys(false)
                            ->integerPrototype()->min(1)->end()
                            ->validate()
                                ->ifTrue(static fn (array $tables): bool => [] !== array_filter(array_keys($tables), static fn (int|string $table): bool => 1 !== preg_match('/^[A-Za-z0-9_]+$/', (string) $table)))
                                ->thenInvalid('A watched table is named with letters, digits and underscores only (for instance "sylius_order"), got %s.')
                            ->end()
                        ->end()
                    ->end()
                ->end()
            ->end()
        ;

        return $treeBuilder;
    }
}
